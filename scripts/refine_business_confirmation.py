def main():
    wb = openpyxl.load_workbook(PATH)
    ws = wb["业务确认清单"]
    # 删除未保留行（从下往上）
    for r in range(ws.max_row, 3, -1):
        code = ws.cell(r, 3).value
        if code and code not in KEEP:
            ws.delete_rows(r, 1)
    # 更新剩余行
    idx = 0
    for r in range(4, ws.max_row + 1):
        code = ws.cell(r, 3).value
        if code not in UPDATES:
            continue
        idx += 1
        item = UPDATES[code]
        values = [
            idx, item["priority"], code, ws.cell(r, 4).value,
            item["current"], item["q"], item["example"], item["options"],
            "", "", item["impact"], item["data"], "待确认",
        ]
        for c, value in enumerate(values, start=1):
            ws.cell(r, c).value = value
        ws.row_dimensions[r].height = 190 if item["priority"] == "P0" else 165
    ws.cell(1, 1).value = "Phase B/C 待确认问题清单（2026-11-01 收敛版）"
    ws.cell(2, 1).value = (
        "已按 2026-11-01 物流专家答复移除已确认问题；本表仅保留仍需确认的 5 项。"
        "技术缺口见 aps_progress_dashboard.md，已确认口径见 aps_implementation_log.md。"
    )
    # 说明页补充
    guide = wb["说明"]
    guide["A1"].value = "APS 业务规则确认清单（2026-11-01 收敛版）"
    guide["B3"].value = (
        "2026-11-01 已按专家答复删除已确认问题，只保留 HC-16、SC-02、HC-09、HC-14、SC-04 五个待确认项。"
        "技术缺口不在本文件，见 aps_progress_dashboard.md。"
    )
    guide["B9"].value = (
        "本版只保留未确认项；已确认问题已从表中删除，历史答复见 Light China APS Rules.xlsx J 列。"
    )
    wb.save(PATH)
    print("saved", PATH, "rows", idx)


if __name__ == "__main__":
    main()
